export function translateProduceName(name: string, lang: SupportedLanguage): string {
  if (PRODUCE_TRANSLATIONS[name] && PRODUCE_TRANSLATIONS[name][lang]) {
    return PRODUCE_TRANSLATIONS[name][lang];
  }
  // Check substring
  for (const [key, map] of Object.entries(PRODUCE_TRANSLATIONS)) {
    if (name.toLowerCase().includes(key.toLowerCase()) && map[lang]) {
      return map[lang];
    }
  }
  return name;
}

export function translateCategoryName(cat: string, lang: SupportedLanguage): string {
  if (CATEGORY_TRANSLATIONS[cat] && CATEGORY_TRANSLATIONS[cat][lang]) {
    return CATEGORY_TRANSLATIONS[cat][lang];
  }
  return cat;
}

export function translateUnitName(unit: string, lang: SupportedLanguage): string {
  const u = unit.toLowerCase();
  if (u.includes('kg')) return UNIT_TRANSLATIONS['kg'][lang] || unit;
  if (u.includes('bunch')) return UNIT_TRANSLATIONS['bunch'][lang] || unit;
  if (u.includes('dozen')) return UNIT_TRANSLATIONS['dozen'][lang] || unit;
  if (u.includes('piece')) return UNIT_TRANSLATIONS['piece'][lang] || unit;
  return unit;
}

